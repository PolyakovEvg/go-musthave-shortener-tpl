// Package audit предоставляет сервис аудита событий.
// Поддерживает отправку событий различным наблюдателям (файл, HTTP).
package audit

// Observer определяет интерфейс для отправки событий аудита.
// Реализации могут отправлять события в файл, по HTTP и т.д.
type Observer interface {
	// Send отправляет событие аудита наблюдателю.
	Send(event AuditEvent) error
}
